/**
 * ============================================================
 * 青少年数据 Hook
 * ============================================================
 *
 * 本文件是整个前端“青少年数据”的统一状态中心。
 *
 * 核心原则：
 *
 *     NocoDB
 *       ↓
 *     youthApi.js
 *       ↓
 *     useYouthData
 *       ↓
 *     allYouthData
 *       ↓
 *     ┌──────────────┬──────────────┬──────────────┐
 *     │ 青少年信息页 │ 一人一档       │ 风险排查页    │
 *     └──────────────┴──────────────┴──────────────┘
 *
 * 对于前端来说：
 *
 *     risks
 *
 * 就是某一个青少年对象的一部分。
 *
 * 虽然数据库中“风险排查记录”是一张独立表，
 * 但前端不能再为它建立第二套数据源。
 *
 * ============================================================
 */

import {
  useEffect,
  useState,
} from 'react'

import {
  fetchYouthRecords,
} from '../api/youthApi'

import {
  normalizeRecord,
} from '../utils/youthNormalizer'

import {
  normalizeRiskRecord,
  sortRisksLatestFirst,
} from '../utils/riskUtils'

import {
  clearYouthCache,
  resetYouthCache,
} from '../store/youthCache'


/**
 * ============================================================
 * 青少年数据 Hook
 * ============================================================
 *
 * 负责：
 *
 * 1. 第一次进入系统时读取全部青少年数据
 * 2. 将后端原始数据标准化
 * 3. 保存 allYouthData
 * 4. 更新某名青少年的风险排查记录
 *
 * 不负责：
 *
 * 1. 页面展示
 * 2. 搜索
 * 3. 筛选
 * 4. 分页
 * 5. Drawer
 * 6. 编辑表单
 *
 * ============================================================
 */

function useYouthData({
  messageApi,

  /**
   * 当前登录用户。
   *
   * 非常重要：
   *
   *     必须在登录成功以后才加载数据。
   *
   * 否则会出现：
   *
   *     登录页阶段（还没有 token）就请求了一次全县数据，
   *     登录成功以后没有重新请求，
   *     乡镇账号因此看到了全县数据。
   */
  user,

  /**
   * 登录态是否已经恢复完成。
   *
   * 刷新页面时用本地 token 换用户信息的那一瞬间
   * 不能发请求。
   */
  ready = true,
}) {

  /**
   * ==========================================================
   * 全部青少年数据
   * ==========================================================
   *
   * 这是整个前端最重要的数据源。
   *
   * 青少年信息页、风险排查页以及一人一档，
   * 最终都应该从这里得到数据。
   *
   * ==========================================================
   */

  const [
    allYouthData,
    setAllYouthData,
  ] = useState([])


  /**
   * ==========================================================
   * 数据加载状态
   * ==========================================================
   */

  const [
    loading,
    setLoading,
  ] = useState(false)


  /**
   * ==========================================================
   * 手动刷新计数
   * ==========================================================
   *
   * 调用 reloadYouthData() 可以强制重新读取一次。
   */

  const [
    reloadKey,
    setReloadKey,
  ] = useState(0)


  /**
   * ==========================================================
   * 账号标识
   * ==========================================================
   *
   * 只要登录账号发生变化（换人登录 / 退出再登录 / 刷新恢复），
   * 这个值就会变，
   * 从而触发重新读取。
   *
   * 这样乡镇账号登录后读到的
   * 一定是本乡镇的数据。
   */

  const userKey = user
    ? [
        user.account || '',
        user.role || '',
        user.town || '',
      ].join('|')
    : ''


  /**
   * ==========================================================
   * 首次加载数据
   * ==========================================================
   */

  useEffect(() => {

    /**
     * ======================================================
     * 没有登录 / 登录态还在恢复：
     *
     * 一个字节的数据都不读。
     * ======================================================
     *
     * 这一步是乡镇账号数据隔离的关键。
     *
     * 以前这里不判断登录状态，
     * 结果在登录页阶段就用“无 token”读了一次全县数据，
     * 登录成功后又不重新读，
     * 于是乡镇账号看到了全县数据。
     */

    if (!ready || !userKey) {
      setAllYouthData([])

      /**
       * 没登录 / 正在换登录态时把缓存清空。
       *
       * 否则退出登录后再用乡镇账号登录，
       * 上一个账号的数据还留在内存里。
       */
      clearYouthCache()

      setLoading(false)

      return
    }

    /**
     * 防止组件卸载以后，
     * 异步请求完成又修改 React 状态。
     */

    let cancelled = false


    /**
     * --------------------------------------------------------
     * 从服务器读取全部青少年数据
     * --------------------------------------------------------
     */

    async function loadYouthData() {

      setLoading(true)

      try {

        /**
         * ====================================================
         * 第一步：
         *
         * 从 youthApi.js 获取服务器数据。
         * ====================================================
         */

        const {
          records: rawRecords,
        } = await fetchYouthRecords()


        /**
         * 如果组件已经卸载，
         * 不再继续处理结果。
         */

        if (cancelled) {
          return
        }


        /**
         * ====================================================
         * 第二步：
         *
         * 将 NocoDB 原始数据统一标准化。
         * ====================================================
         */

        const records =
          rawRecords.map(
            (
              item,
              index,
            ) =>
              normalizeRecord(
                item,
                index,
              ),
          )


        /**
         * ====================================================
         * 第三步：
         *
         * 保存到唯一的前端数据源。
         * ====================================================
         */

        setAllYouthData(
          records,
        )

        /**
         * 整体替换前端内存缓存。
         *
         * 这里必须是 replace 而不是累加：
         *
         *     后端返回的就是“这个账号能看到的全部数据”，
         *     缓存必须和它完全一致。
         *
         *     累加的话，换账号登录后
         *     上一个账号的数据会残留在缓存里，
         *     帮扶页一合并就又全冒出来了
         *     （乡镇账号因此能看到全县 1181 条）。
         *
         * 这样无论是“新增 / 编辑”还是“刷新页面后重新读取”，
         * 内存缓存始终与服务器数据保持一致，
         * 帮扶管理页等其它页面都能立刻读到最新记录。
         */
        resetYouthCache(
          records,
        )

      } catch (error) {

        /**
         * 如果组件已经卸载，
         * 不再继续处理错误。
         */

        if (cancelled) {
          return
        }


        console.error(
          '读取青少年数据失败：',
          error,
        )


        /**
         * 页面提示。
         */

        messageApi.error(
          `读取数据库失败：${
            error?.message ||
            '未知错误'
          }`,
        )


        /**
         * 读取失败时清空数据，
         * 缓存也一起清掉，
         * 避免残留上一次的旧数据被合并出来。
         */

        setAllYouthData([])

        clearYouthCache()

      } finally {

        /**
         * 请求结束以后关闭 loading。
         */

        if (!cancelled) {
          setLoading(false)
        }

      }
    }


    /**
     * 执行第一次加载。
     */

    loadYouthData()


    /**
     * ========================================================
     * 组件卸载
     * ========================================================
     */

    return () => {
      cancelled = true
    }

  }, [
    messageApi,
    userKey,
    ready,
    reloadKey,
  ])


  /**
   * ==========================================================
   * 更新某一名青少年的风险排查记录
   * ==========================================================
   *
   * 这是本次修改最重要的部分。
   *
   * ----------------------------------------------------------
   *
   * 调用方：
   *
   *     RiskPage
   *
   * 保存成功以后拿到：
   *
   *     result.record
   *
   * 然后调用：
   *
   *     updateYouthRisks(
   *       youthId,
   *       result.record,
   *     )
   *
   * ----------------------------------------------------------
   *
   * 注意：
   *
   * 这里绝对不重新请求数据库。
   *
   * 因为服务器刚刚已经把最终保存成功的记录返回给我们。
   *
   * 我们直接使用这条“服务器确认成功”的记录，
   * 更新 allYouthData。
   *
   * ----------------------------------------------------------
   *
   * 最终数据流：
   *
   *     POST
   *       ↓
   *     服务器保存成功
   *       ↓
   *     返回 record
   *       ↓
   *     updateYouthRisks()
   *       ↓
   *     allYouthData
   *       ↓
   *     React 自动重新渲染所有页面
   *
   * ==========================================================
   */



  /**
   * ==========================================================
   * 对外返回
   * ==========================================================
   */

  /**
   * ==========================================================
   * 手动重新读取
   * ==========================================================
   */

  function reloadYouthData() {
    setReloadKey(
      (value) => value + 1,
    )
  }

  return {
    allYouthData,

    setAllYouthData,

    loading,

    reloadYouthData,
  }
}


/**
 * ============================================================
 * 导出
 * ============================================================
 */

export {
  useYouthData,
}